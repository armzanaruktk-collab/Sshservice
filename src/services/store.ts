export const AppStore = {
  getProfiles(): SshProfile[] {
    try {
      const data = localStorage.getItem('worldvpn_profiles');
      if (data) {
        const parsed = JSON.parse(data);
        if (Array.isArray(parsed) && parsed.length > 0) return parsed;
      }
    } catch (e) {
      console.error(e);
    }
    return DEFAULT_SERVERS;
  },

  saveProfiles(profiles: SshProfile[]) {
    try {
      localStorage.setItem('worldvpn_profiles', JSON.stringify(profiles));
    } catch (e) {
      console.error(e);
    }
  },

  getSelectedId(): string | null {
    return localStorage.getItem('worldvpn_selected_id') || 'server-japan-217';
  },

  setSelectedId(id: string | null) {
    if (id) {
      localStorage.setItem('worldvpn_selected_id', id);
    } else {
      localStorage.removeItem('worldvpn_selected_id');
    }
  },

  getPayloads(): PayloadItem[] {
    try {
      const data = localStorage.getItem('worldvpn_payloads');
      if (data) {
        const parsed = JSON.parse(data);
        if (Array.isArray(parsed) && parsed.length > 0) return parsed;
      }
    } catch (e) {
      console.error(e);
    }
    return DEFAULT_PAYLOADS;
  },

  savePayloads(payloads: PayloadItem[]) {
    try {
      localStorage.setItem('worldvpn_payloads', JSON.stringify(payloads));
    } catch (e) {
      console.error(e);
    }
  },

  getSelectedPayloadId(): string | null {
    return localStorage.getItem('worldvpn_selected_payload_id') || 'payload-v1';
  },

  setSelectedPayloadId(id: string | null) {
    if (id) {
      localStorage.setItem('worldvpn_selected_payload_id', id);
    } else {
      localStorage.removeItem('worldvpn_selected_payload_id');
    }
  },

  getSettings(): VpnSettings {
    try {
      const data = localStorage.getItem('worldvpn_settings');
      if (data) {
        const parsed = JSON.parse(data);
        return {
          ...DEFAULT_SETTINGS,
          ...parsed,
          advanced: { ...DEFAULT_SETTINGS.advanced, ...(parsed.advanced || {}) },
        };
      }
    } catch (e) {
      console.error(e);
    }
    return DEFAULT_SETTINGS;
  },

  saveSettings(settings: VpnSettings) {
    try {
      localStorage.setItem('worldvpn_settings', JSON.stringify(settings));
    } catch (e) {
      console.error(e);
    }
  },
};
